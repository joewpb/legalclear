def build_artifact(
    artifact_id: str,
    claim: dict,
    events: list[dict],
    deadlines: list[dict],
    details: dict,
) -> tuple[bytes, str, str]:
    """Return (bytes, mime, filename) for one artifact.

    Raises KeyError for an unknown artifact_id (the router maps that to 404).
    """
    meta = ARTIFACT_CATALOG[artifact_id]
    filename = f"{artifact_id}_{datetime.now(timezone.utc).strftime('%Y%m%d')}.{meta['ext']}"

    if artifact_id == "claim_log":
        return _render_pdf(_claim_log_html(claim, events, details)), meta["mime"], filename
    if artifact_id == "policy_request_letter":
        return _render_pdf(_policy_request_html(details)), meta["mime"], filename
    if artifact_id == "vacancy_notice":
        return _render_pdf(_vacancy_notice_html(details)), meta["mime"], filename
    if artifact_id == "work_auth_rider":
        return _render_pdf(_work_auth_rider_html(details)), meta["mime"], filename
    if artifact_id == "packout_demand":
        return _render_pdf(_packout_demand_html(details)), meta["mime"], filename
    if artifact_id == "contents_inventory_csv":
        return _contents_inventory_csv(details), meta["mime"], filename
    if artifact_id == "contents_inventory_pdf":
        return _render_pdf(_contents_inventory_html(details)), meta["mime"], filename
    if artifact_id == "depreciation_challenge":
        return _render_pdf(_depreciation_challenge_html(details)), meta["mime"], filename
    if artifact_id == "supplement_cover":
        return _render_pdf(_supplement_cover_html(details)), meta["mime"], filename
    if artifact_id == "demand_letter":
        return _render_pdf(_demand_letter_html(details)), meta["mime"], filename
    if artifact_id == "dfs_mediation_prefill":
        return _render_pdf(_dfs_mediation_prefill_html(details)), meta["mime"], filename
    if artifact_id == "deadline_calendar_ics":
        return _deadline_calendar_ics(claim, deadlines), meta["mime"], filename
    raise KeyError(artifact_id)
