"""I-7 — deterministic claim artifacts (Phase I finale, 2026-08-23).

Every artifact is a DRAFT document the user reviews, edits, and sends
themselves (spec §9.1: information and document preparation the consumer
performs themselves — never negotiation on their behalf). No LLM anywhere
in this module. Citations in letter bodies come ONLY from the P&C curated
set (agents.pc_citations).

Artifact catalog — spec §6, both batches:

  Batch A (early claim): claim_log, policy_request_letter, vacancy_notice,
      work_auth_rider, packout_demand, contents_inventory (CSV + PDF)
  Batch B (dispute): depreciation_challenge, supplement_cover,
      demand_letter, dfs_mediation_prefill, deadline_calendar (.ics)

User facts come from the claim's ``details`` jsonb (user-supplied only,
never inferred from documents). Missing facts render as bracketed
placeholders and are listed in ``missing_fields`` — the UI highlights them
rather than the generator inventing values.
"""

from __future__ import annotations

import csv
import html
import io
from datetime import date, datetime, timezone

_DRAFT_NOTE = (
    "This is a draft document prepared by the policyholder using LegalClear "
    "information tools. It is a starting point, not legal advice. Review it, "
    "correct it, and send it yourself."
)

_DETAIL_KEYS = (
    "insured_name", "insured_address", "insurer_name", "claim_number",
    "policy_number", "adjuster_name", "property_address",
    "fire_report_number", "mortgage_company", "phone_number",
)


def _fmt_date(raw: str | None, placeholder: str = "[date]") -> str:
    if not raw:
        return placeholder
    try:
        return date.fromisoformat(raw).strftime("%B %d, %Y")
    except ValueError:
        return raw


def _d(details: dict, key: str, placeholder: str) -> str:
    value = (details or {}).get(key)
    return html.escape(str(value)) if value else placeholder


def missing_fields(details: dict) -> list[str]:
    return [k for k in _DETAIL_KEYS if not (details or {}).get(k)]


