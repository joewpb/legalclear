_INVENTORY_COLUMNS = [
    "room", "item", "brand", "model", "serial", "qty", "age_years",
    "price_paid", "condition", "cost_new_today", "price_source",
]


def _contents_inventory_csv(details: dict) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(_INVENTORY_COLUMNS)
    writer.writerow(["example: kitchen", "toaster", "Cuisinart", "CPT-122",
                     "12345XYZ", "1", "3", "45.00", "good", "59.99",
                     "amazon.com"])
    return buf.getvalue().encode("utf-8")


def _contents_inventory_html(details: dict) -> str:
    cols = "".join(f"<th style='padding:6px;border:1px solid #ccc'>{c}</th>" for c in _INVENTORY_COLUMNS)
    body = f"""
<p><strong>Contents inventory</strong></p>
<p>One row per item. Whoever writes the list controls what gets paid for it.
For proof when receipts burned: credit card and bank statements, email order
confirmations, online order history, warranty registrations, photos of the
home, social media, photos friends and family took, a prior mover's
inventory.</p>
<p style="font-size:10pt;color:#555">One hard rule: never list something you
did not own. Honest mistakes on a reconstructed list are normal; deliberate
padding is insurance fraud and can void the whole claim.</p>
<table style='border-collapse:collapse;width:100%;font-size:9pt'>
<tr>{cols}</tr>
<tr>{''.join(f"<td style='padding:6px;border:1px solid #ccc'>&nbsp;</td>" for _ in _INVENTORY_COLUMNS)}</tr>
</table>
"""
    return _letter_html(body, details, "Contents inventory")


