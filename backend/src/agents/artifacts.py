def _ics_escape(text: str) -> str:
    return (text.replace("\\", "\\\\").replace(";", "\\;")
            .replace(",", "\\,").replace("\n", "\\n"))


def _deadline_calendar_ics(claim: dict, deadlines: list[dict]) -> bytes:
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//LegalClear//Claim Deadlines//EN"]
    for i, dl in enumerate(deadlines):
        due = dl.get("due_date", "")
        if not due:
            continue
        uid = f"legalclear-{hash(str(claim.get('id')) + due + str(i)) & 0xFFFFFFFF:08x}"
        summary = _ics_escape(f"{dl.get('label', 'Deadline')} — {dl.get('governing_rule', '')}")
        lines += [
            "BEGIN:VEVENT",
            f"UID:{uid}@legalclear",
            f"DTSTAMP:{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}",
            f"DTSTART;VALUE=DATE:{due.replace('-', '')}",
            f"SUMMARY:{summary}",
            "END:VEVENT",
        ]
    lines.append("END:VCALENDAR")
    return ("\r\n".join(lines) + "\r\n").encode("utf-8")


