def _claim_log_html(claim: dict, events: list[dict], details: dict) -> str:
    rows = []
    for event in sorted(events, key=lambda e: e.get("occurred_at") or "", reverse=True):
        when = _fmt_date((event.get("occurred_at") or "")[:10])
        name = html.escape(str(event.get("trigger_name")))
        note = html.escape(str(event.get("note") or ""))
        rows.append(f"<tr><td style='padding:6px 12px 6px 0;white-space:nowrap'>{when}</td>"
                    f"<td style='padding:6px 12px;font-weight:bold'>{name}</td>"
                    f"<td style='padding:6px 0'>{note}</td></tr>")
    table = ("<table style='border-collapse:collapse;width:100%'>"
             + "".join(rows) + "</table>") if rows else "<p>No events recorded yet.</p>"
    loss = _fmt_date((claim.get("date_of_loss") or "")[:10], "[date of loss]")
    body = f"""
<p><strong>Claim log</strong> — peril: {html.escape(str(claim.get("peril") or "fire"))};
date of loss: {loss}.</p>
{table}
<p style="font-size:10pt;color:#555">Every entry is timestamped when recorded.
Add to this log every time anything happens on the claim.</p>
"""
    return _letter_html(body, details, "Claim log")


